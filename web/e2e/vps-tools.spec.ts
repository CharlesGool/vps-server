test('迷你网盘: 上传, 生成并打开下载链接, 删除', async ({ page }) => {
  await open(page, '/files')
  const upload = page.locator('main section', { has: page.getByRole('heading', { name: '本地上传', exact: true }) })
  await upload.locator('input[type=file]').setInputFiles({ name: 'hello.txt', mimeType: 'text/plain', buffer: Buffer.from('hello vps-server\n') })
  await upload.getByRole('button', { name: '上传' }).click()
  const table = page.locator('main section', { has: page.getByRole('heading', { name: '文件', exact: true }) })
  await expect(table.getByRole('cell', { name: 'hello.txt', exact: true })).toBeVisible()
  await table.getByRole('button', { name: '更多操作 hello.txt' }).click()
  await page.getByRole('menuitem', { name: /下载链接/ }).click()
  const dialog = page.getByRole('dialog', { name: 'hello.txt 的下载链接' })
  await dialog.getByRole('button', { name: '生成下载链接' }).click()
  const field = dialog.locator('input[readonly]')
  await expect(field).toHaveValue(/\/f\//)
  const link = await field.inputValue()
  const response = await page.request.get(link)
  expect(await response.text()).toBe('hello vps-server\n')
  await dialog.getByRole('button', { name: '关闭', exact: true }).first().click()
  await table.getByRole('button', { name: '更多操作 hello.txt' }).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '删除' }).click()
  await expect(table.getByText('还没有文件。')).toBeVisible()
})

